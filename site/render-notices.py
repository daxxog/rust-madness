#!/usr/bin/env python3
"""Regenerate the rendered-notices block inside index.html.

The footer's three notice documents are NOT hand-written HTML. The canonical
sources are the markdown/text files in the parent directory (public/):

    public/NOTICES.md  public/PROVENANCE.md  public/LICENSE

This script reads those files, converts them to HTML with a deliberately tiny
markdown-to-HTML converter, and replaces everything between the two markers in
index.html:

    <!-- BEGIN GENERATED NOTICES ... -->
    ...
    <!-- END GENERATED NOTICES -->

Run it from anywhere:

    python3 public/site/render-notices.py

Edit the markdown, not the generated block, and the footer cannot drift.
"""

from __future__ import annotations

import html
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
PARENT = HERE.parent  # public/ — the canonical sources live here

BEGIN = "<!-- BEGIN GENERATED NOTICES"
END = "<!-- END GENERATED NOTICES -->"

# (source file, element id, section heading) — order is the footer order.
DOCS = [
    ("NOTICES.md", "notices-doc", "Notices"),
    ("PROVENANCE.md", "provenance-doc", "Provenance"),
    ("LICENSE", "license-doc", "License (MIT)"),
]


def inline(text: str) -> str:
    """Escape first, then apply the handful of inline constructs we use."""
    s = html.escape(text, quote=False)
    s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
    s = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', s)
    return s


def md_to_html(md: str) -> str:
    """Headings, bullet lists (with wrapped continuations) and paragraphs."""
    out: list[str] = []
    para: list[str] = []
    items: list[str] = []

    def flush_para() -> None:
        if para:
            out.append("<p>" + inline(" ".join(para)) + "</p>")
            para.clear()

    def flush_list() -> None:
        if items:
            out.append("<ul>" + "".join(f"<li>{inline(x)}</li>" for x in items) + "</ul>")
            items.clear()

    for raw in md.splitlines():
        line = raw.rstrip()
        if not line.strip():
            flush_para()
            flush_list()
            continue
        heading = re.match(r"^(#{1,6})\s+(.*)$", line)
        if heading:
            flush_para()
            flush_list()
            level = "h3" if len(heading.group(1)) <= 2 else "h4"
            out.append(f"<{level}>{inline(heading.group(2))}</{level}>")
            continue
        if line.startswith("- "):
            flush_para()
            items.append(line[2:].strip())
            continue
        if items:
            # A wrapped continuation line belongs to the previous bullet.
            items[-1] += " " + line.strip()
            continue
        para.append(line.strip())

    flush_para()
    flush_list()
    return "\n".join(out)


def build_block() -> str:
    parts: list[str] = []
    for filename, element_id, heading in DOCS:
        md = (PARENT / filename).read_text(encoding="utf-8")
        # Each doc's own top-level heading is redundant with <h2> below.
        md = re.sub(r"^#\s+.*\n", "", md, count=1)
        body = md_to_html(md)
        parts.append(
            f'    <section class="doc" id="{element_id}">\n'
            f"      <h2>{heading}</h2>\n"
            f'      <div class="doc-body">\n{body}\n      </div>\n'
            f"    </section>"
        )
    return "\n\n".join(parts)


def main() -> None:
    page_path = HERE / "index.html"
    page = page_path.read_text(encoding="utf-8")
    begin_at = page.index(BEGIN)
    end_at = page.index(END, begin_at) + len(END)
    block = (
        "<!-- BEGIN GENERATED NOTICES — generated by render-notices.py; "
        "do not edit by hand -->\n"
        + build_block()
        + "\n    "
        + END
    )
    page_path.write_text(page[:begin_at] + block + page[end_at:], encoding="utf-8")
    print("rendered notices into", page_path)


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Mechanically extract UlawUtils.s2u_lut into a Rust const.

Reads reference/vineflower/UlawUtils.java, parses the 8192 signed byte
literals of `s2u_lut`, checks the table md5 against the JDK-printed value
(e29ced91ea43dede8cb8fca51841ed95, see the modpin scratch rig), and emits
a Rust `const S2U_LUT: [i8; 8192]` block on stdout.

The table is NOT standard G.711 mu-law (780/8192 entries differ from the
textbook encoder), so it is transcribed literally instead of recomputed.
"""
import hashlib
import re
import sys

SRC = "reference/vineflower/UlawUtils.java"
EXPECT_MD5 = "e29ced91ea43dede8cb8fca51841ed95"


def main() -> None:
    text = open(SRC).read()
    body = text.split("s2u_lut", 1)[1].split("};", 1)[0]
    nums = [int(x) for x in re.findall(r"(?<![0-9A-Za-z_])-?\d+", body)]
    assert len(nums) == 8192, f"expected 8192 entries, got {len(nums)}"
    assert all(-128 <= n <= 127 for n in nums)
    raw = bytes(n & 0xFF for n in nums)
    digest = hashlib.md5(raw).hexdigest()
    assert digest == EXPECT_MD5, f"table md5 {digest} != {EXPECT_MD5}"
    print(f"// Generated by tools/gen-s2u-lut.py from {SRC}.", file=sys.stderr)
    print(f"// Table md5: {digest} (matches JDK UlawUtils.s2u_lut).", file=sys.stderr)
    print("// This is NOT standard G.711 mu-law; transcribed literally.", file=sys.stderr)
    print("const S2U_LUT: [i8; 8192] = [")
    for i in range(0, 8192, 16):
        print("    " + ", ".join(str(n) for n in nums[i : i + 16]) + ",")
    print("];")


if __name__ == "__main__":
    main()

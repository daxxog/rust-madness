/// `beattrack` (ModSlayer.java:364-438): per-tick continuous effects
/// (volume slide, portamento, vibrato, arpeggio) on ONE track. A free
/// function so the engine loop can hand out `&mut tracks[i]` while the
/// Phase B mirror drives a caller-owned track exactly like Java's
/// `beattrack(ModTrackInfo)`.
fn beattrack_body(s3m: bool, t: &mut ModTrackInfo) {
    if t.period_low_limit == 0 {
        t.period_low_limit = 1;
    }

    if (t.effect & 1) != 0 {
        t.volume += t.vol_slide;
        t.volume = t.volume.clamp(0, 64);
    }

    if (t.effect & 2) != 0 {
        t.period += t.port_down;
        if t.period > t.period_high_limit {
            t.period = t.period_high_limit;
        }
        t.pitch = t.finetune_rate / t.period;
    }

    if (t.effect & 4) != 0 {
        t.period -= t.port_up;
        if t.period < t.period_low_limit {
            if s3m {
                t.period = t.period_high_limit;
            } else {
                t.period = t.period_low_limit;
            }
        }
        t.pitch = t.finetune_rate / t.period;
    }

    if (t.effect & 32) != 0 {
        if t.portto < t.period {
            t.period += t.port_inc;
            if t.period > t.portto {
                t.period = t.portto;
            }
        } else if t.portto > t.period {
            t.period -= t.port_inc;
            if t.period < t.portto {
                t.period = t.portto;
            }
        }
        t.pitch = t.finetune_rate / t.period;
    }

    if (t.effect & 8) != 0 {
        t.vibpos += t.vib_rate << 2;
        let mut var2 = (SINTABLE[((t.vibpos >> 2) & 31) as usize] * t.vib_depth) >> 7;
        if (t.vibpos & 128) != 0 {
            var2 = -var2;
        }
        var2 = (var2 + t.period).clamp(t.period_low_limit, t.period_high_limit);
        t.pitch = t.finetune_rate / var2;
    }

    if (t.effect & 16) != 0 {
        t.pitch = t.finetune_rate / t.arp[t.arpindex as usize];
        t.arpindex += 1;
        if t.arpindex >= 3 {
            t.arpindex = 0;
        }
    }
}

impl ModSlayer {
    /// `beattrack(ModTrackInfo)` (ModSlayer.java:364): the Java call shape —
    /// a caller-owned track — for the Phase B mirror's crafted-track pins;
    /// the engine loop drives `beattrack_body` directly.
    #[allow(dead_code)] // pinned only by the cfg(test) mirror (TModSlayer/TModEdges); the engine loop calls beattrack_body
    pub(crate) fn beattrack(&mut self, t: &mut ModTrackInfo) {
        beattrack_body(self.song.s3m, t);
    }

    /// `mixtrack_16_mono` (ModSlayer.java:440-503): resample one channel
    /// into the tick buffer with 12-bit fractional position (`ERROR_SHIFT`).
    ///
    /// Buffer accumulation wraps exactly like Java `int` (`wrapping_add`);
    /// all other ops are in ranges that cannot overflow for real modules.
    fn mixtrack_16_mono(&mut self, idx: usize, buf: &mut [i32], off: usize, len: i32) {
        // Copy the (Copy) mixer staging + track scalars before taking the
        // track borrow, mirroring the Java reads (ModSlayer.java:441-446).
        let vol =
            (self.vol_adj[self.tracks[idx].volume as usize] * self.gain) >> (self.vol_shift + 8);
        let pitch = self.tracks[idx].pitch;
        let replen = self.tracks[idx].replen;
        let repeat = self.tracks[idx].repeat;
        let length = self.tracks[idx].length;
        let mut pos = self.tracks[idx].position;
        let mut err = self.tracks[idx].error;
        let t = &mut self.tracks[idx];
        let samples = &t.samples;
        let frac = pitch & 4095;
        let step = pitch >> 12;
        if replen < 3 {
            let end = length;
            if pos >= end {
                return;
            }
            let lim = off + len as usize;
            let mut o = off;
            if pitch < 4096 {
                while pos < end && o < lim {
                    let a = samples[pos as usize] as i32;
                    let b = samples[(pos + 1) as usize] as i32;
                    buf[o] = buf[o].wrapping_add(((a * (4096 - err) + b * err) * vol) >> 12);
                    o += 1;
                    let e = err + frac;
                    pos += step + (e >> 12);
                    err = e & 4095;
                }
            } else {
                while pos < end && o < lim {
                    buf[o] = buf[o].wrapping_add(samples[pos as usize] as i32 * vol);
                    o += 1;
                    let e = err + frac;
                    pos += step + (e >> 12);
                    err = e & 4095;
                }
            }
            t.error = err;
            t.position = pos;
        } else {
            let end = replen + repeat;
            let mut o = off;
            if pitch < 4096 {
                let mut n = len;
                while n > 0 {
                    if pos >= end {
                        pos -= replen;
                    }
                    let a = samples[pos as usize] as i32;
                    let b = samples[(pos + 1) as usize] as i32;
                    buf[o] = buf[o].wrapping_add(((a * (4096 - err) + b * err) * vol) >> 12);
                    o += 1;
                    let e = err + frac;
                    pos += step + (e >> 12);
                    err = e & 4095;
                    n -= 1;
                }
            } else {
                let mut n = len;
                while n > 0 {
                    if pos >= end {
                        pos -= replen;
                    }
                    buf[o] = buf[o].wrapping_add(samples[pos as usize] as i32 * vol);
                    o += 1;
                    let e = err + frac;
                    pos += step + (e >> 12);
                    err = e & 4095;
                    n -= 1;
                }
            }
            t.error = err;
            t.position = pos;
        }
    }

    /// `make_vol_table8` (ModSlayer.java:514-521): the 8-bit mix path's
    /// volume table. Dead in practice — `turnbytes` forces `bit16 = true`
    /// before `startplaying` — but kept for shape.
    fn make_vol_table8(&mut self) {
        self.vol_table = vec![0i8; 16640];
        let mut v: usize = 0;
        loop {
            // (vol_adj[v >> 8] * (byte)v) >> (8 + vol_shift), narrowed to byte
            self.vol_table[v] =
                ((self.vol_adj[v >> 8] * ((v as i8) as i32)) >> (8 + self.vol_shift)) as i8;
            v += 1;
            if v >= 16640 {
                break;
            }
        }
    }

    /// `updatetracks` (ModSlayer.java:523-551): advance one row, decoding
    /// each channel's 4 pattern bytes via `get_track`.
    pub(crate) fn updatetracks(&mut self) {
        self.tempo_wait = self.tempo;
        if self.row >= 64 {
            if self.order_pos >= self.song.song_length_patterns {
                self.order_pos = 0;
                self.nloops -= 1;
                if self.nloops == 0 {
                    self.mod_done = true;
                }
            }
            self.row = self.break_row;
            self.break_row = 0;
            // Dead in Java too: `positions` is `byte[]`, so the widened
            // value is in [-128, 127] and never equals 255. Kept verbatim.
            if (self.song.positions[self.order_pos as usize] as i32) == 255 {
                self.order_pos = 0;
                self.row = 0;
            }
            let pat_idx = self.song.positions[self.order_pos as usize] as usize;
            self.patt = self.song.patterns[pat_idx].clone();
            self.pattofs = self.row * 4 * self.numtracks;
            self.order_pos += 1;
        }

        self.row += 1;

        for i in 0..self.numtracks as usize {
            let off = self.pattofs;
            self.pattofs = self.get_track(i, off);
        }
    }

    /// `turnbytes` (ModSlayer.java:553-621): mix the whole song (single
    /// loop) to μ-law bytes. `var4` is never written — every tick starts
    /// from a zeroed mix buffer, exactly as in Java.
    pub fn turnbytes(&mut self) -> Vec<i8> {
        self.bit16 = true;
        let loud = self.loud;
        self.startplaying(loud);
        let mut var3 = vec![0i32; self.mixspeed as usize];
        let var4 = vec![0i32; self.mixspeed as usize];
        let mut var5 = vec![0i32; 3500000];
        let mut var6: usize = 0;

        while !self.mod_done {
            self.tempo_wait -= 1;
            if self.tempo_wait > 0 {
                for i in 0..self.numtracks as usize {
                    let s3m = self.song.s3m;
                    beattrack_body(s3m, &mut self.tracks[i]);
                }
            } else {
                self.updatetracks();
            }

            var3[..self.bpm_samples as usize].copy_from_slice(&var4[..self.bpm_samples as usize]);

            for i in 0..self.numtracks as usize {
                let bpm = self.bpm_samples;
                self.mixtrack_16_mono(i, &mut var3, 0, bpm);
            }

            let mut var7 = self.bpm_samples;
            if self.oversample > 1 {
                // Unreachable (`oversample` is always 1); transcribed for
                // shape (ModSlayer.java:577-596).
                let mut var8: usize = 0;
                var7 = self.bpm_samples / self.oversample;
                if self.oversample == 2 {
                    for var12 in 0..var7 as usize {
                        var3[var12] = (var3[var8] + var3[var8 + 1]) >> 1;
                        var8 += 2;
                    }
                } else {
                    for var11 in 0..var7 as usize {
                        let mut var9 = var3[var8];
                        var8 += 1;
                        for _ in 1..self.oversample {
                            var9 += var3[var8];
                            var8 += 1;
                        }
                        var3[var11] = var9 / self.oversample;
                    }
                }
            }

            for &s in var3.iter().take(var7 as usize) {
                if var6 < 3500000 {
                    var5[var6] = s;
                    var6 += 1;
                }
            }
        }

        // Two in-place smoothing passes (ModSlayer.java:606-612).
        for var14 in 2..var6 {
            var5[var14] = (var5[var14] + var5[var14 - 2]) / 2;
        }
        for var15 in 57..var6 {
            var5[var15] = (var5[var15] + var5[var15] + var5[var15 - 50]) / 3;
        }

        var5[..var6].iter().map(|&s| linear2ulawclip(s)).collect()
    }

    /// `get_track` (ModSlayer.java:623-774): decode one channel's 4 pattern
    /// bytes. Returns the next pattern offset. Takes the track index (rather
    /// than `&mut ModTrackInfo` as in Java) for borrow reasons; the `case
    /// 5 → 6 → 10` fallthrough (port-to AND vol-slide, ModSlayer.java:703-711)
    /// is reproduced exactly.
    fn get_track(&mut self, idx: usize, mut off: i32) -> i32 {
        let b0 = self.patt[off as usize] as i32;
        let b1 = self.patt[(off + 1) as usize] as i32;
        let b2 = self.patt[(off + 2) as usize] as i32;
        let b3 = self.patt[(off + 3) as usize] as i32;
        let mut var4 = b0 & 240;
        let mut var5 = (b0 & 15) << 8;
        var5 |= b1 & 255;
        let var6 = b2 & 15;
        var4 |= (b2 & 240) >> 4;
        let mut var7 = b3;
        off += 4;

        self.tracks[idx].effect = 0;
        if var4 != 0 {
            // `--var4` in Java: instrument numbers are 1-based.
            let inst = self.song.insts[(var4 - 1) as usize].clone();
            let t = &mut self.tracks[idx];
            t.volume = inst.volume;
            t.length = inst.sample_length;
            t.repeat = inst.repeat_point;
            t.replen = inst.repeat_length;
            t.finetune_rate = inst.finetune_rate;
            t.samples = inst.samples.clone();
            t.period_low_limit = inst.period_low_limit;
            t.period_high_limit = inst.period_high_limit;
        }

        if var5 != 0 {
            let t = &mut self.tracks[idx];
            t.portto = var5;
            if var6 != 3 && var6 != 5 {
                let fr = t.finetune_rate;
                t.start_period = var5;
                t.period = var5;
                t.pitch = fr / var5;
                t.position = 0;
            }
        }

        if var6 != 0 || var7 != 0 {
            match var6 {
                0 => {
                    // Arpeggio: scan up to the note at/above the period
                    // (ModSlayer.java:655-667). `var19` can reach 48; the
                    // +15 offsets stay inside `PERIOD_SET` (84 entries).
                    let period = self.tracks[idx].period;
                    let mut var19: i32 = 12;
                    while period < PERIOD_SET[var19 as usize] {
                        var19 += 1;
                        if var19 >= 48 {
                            break;
                        }
                    }
                    let t = &mut self.tracks[idx];
                    t.arp[0] = PERIOD_SET[var19 as usize];
                    t.arp[1] = PERIOD_SET[(var19 + (var7 & 15)) as usize];
                    t.arp[2] = PERIOD_SET[(var19 + ((var7 & 240) >> 4)) as usize];
                    t.arpindex = 0;
                    t.effect |= 16;
                }
                1 => {
                    self.tracks[idx].effect |= 4;
                    if var7 != 0 {
                        self.tracks[idx].port_up = var7;
                    }
                }
                2 => {
                    self.tracks[idx].effect |= 2;
                    if var7 != 0 {
                        self.tracks[idx].port_down = var7;
                    }
                }
                3 => {
                    if var7 != 0 {
                        self.tracks[idx].port_inc = var7 & 0xFF;
                    }
                    self.tracks[idx].effect |= 32;
                }
                4 => {
                    if (var7 & 15) != 0 {
                        self.tracks[idx].vib_depth = var7 & 15;
                    }
                    if (var7 & 240) != 0 {
                        self.tracks[idx].vib_rate = (var7 & 240) >> 4;
                    }
                    if var5 != 0 {
                        self.tracks[idx].vibpos = 0;
                    }
                    self.tracks[idx].effect |= 8;
                }
                // Cases 5/6 fall through into 10 in Java (no breaks).
                5 => {
                    self.tracks[idx].effect |= 32;
                    let t = &mut self.tracks[idx];
                    t.vol_slide = ((var7 & 240) >> 4) - (var7 & 15);
                    t.effect |= 1;
                }
                6 => {
                    self.tracks[idx].effect |= 8;
                    let t = &mut self.tracks[idx];
                    t.vol_slide = ((var7 & 240) >> 4) - (var7 & 15);
                    t.effect |= 1;
                }
                10 => {
                    let t = &mut self.tracks[idx];
                    t.vol_slide = ((var7 & 240) >> 4) - (var7 & 15);
                    t.effect |= 1;
                }
                9 => {
                    if var7 == 0 {
                        var7 = self.tracks[idx].oldsampofs;
                    }
                    self.tracks[idx].oldsampofs = var7;
                    self.tracks[idx].position = (var7 & 0xFF) << 8;
                }
                12 => {
                    if (0..=64).contains(&var7) {
                        self.tracks[idx].volume = var7;
                    } else {
                        self.tracks[idx].volume = 64;
                    }
                }
                13 => {
                    self.break_row = ((var7 & 240) >> 4) * 10 + (var7 & 15);
                    self.row = 64;
                }
                14 => {
                    let var9 = var7 & 240;
                    var7 &= 15;
                    match var9 {
                        1 => {
                            let t = &mut self.tracks[idx];
                            t.period += var7;
                            if t.period > t.period_high_limit {
                                t.period = t.period_high_limit;
                            }
                            let fr = t.finetune_rate;
                            t.pitch = fr / t.period;
                            return off;
                        }
                        2 => {
                            let t = &mut self.tracks[idx];
                            t.period -= var7;
                            if t.period < t.period_low_limit {
                                t.period = t.period_low_limit;
                            }
                            let fr = t.finetune_rate;
                            t.pitch = fr / t.period;
                            return off;
                        }
                        _ => return off,
                    }
                }
                15 => {
                    if var7 != 0 {
                        // `var7 &= 255`: the effect byte is signed, so this
                        // maps [-128, -1] to [128, 255] (ModSlayer.java:761).
                        var7 &= 255;
                        if var7 <= 32 {
                            self.tempo = var7;
                            self.tempo_wait = var7;
                        } else {
                            self.bpm = var7;
                            // `(103 * var7) >> 8`: `*` binds tighter than
                            // `>>` (ModSlayer.java:767).
                            self.bpm_samples =
                                self.samplingrate / ((103 * var7) >> 8) * self.oversample;
                        }
                    }
                }
                _ => {}
            }
        }

        off
    }

    /// `startplaying` (ModSlayer.java:776-819): reset the song state and
    /// derive per-instrument finetune rates for the output rate.
    pub(crate) fn startplaying(&mut self, loud: bool) {
        self.vol_adj = if loud {
            &LOUD_VOL_ADJ[..]
        } else {
            &NORMAL_VOL_ADJ[..]
        };
        self.mixspeed = self.samplingrate * self.oversample;
        self.order_pos = 0;
        self.tempo_wait = self.def_tempo;
        self.tempo = self.def_tempo;
        self.bpm = self.def_bpm;
        self.row = 64;
        self.break_row = 0;
        // `24 * bpm / 60` evaluates left-to-right (ModSlayer.java:784).
        self.bpm_samples = self.samplingrate / ((24 * self.bpm) / 60) * self.oversample;
        self.numtracks = self.song.numtracks;
        self.tracks = Vec::with_capacity(self.numtracks as usize);
        for _ in 0..self.numtracks {
            self.tracks.push(ModTrackInfo::new());
        }

        if self.song.s3m {
            for inst in self.song.insts.iter_mut() {
                // `((428L * finetune_value) << 8) / mixspeed`: `*` binds
                // tighter than `<<` (ModSlayer.java:795).
                inst.finetune_rate =
                    (((428i64 * inst.finetune_value as i64) << 8) / self.mixspeed as i64) as i32;
                inst.period_low_limit = 14;
                inst.period_high_limit = 1712;
            }
        } else {
            for inst in self.song.insts.iter_mut() {
                // `22748294283264 / (mixspeed * (1536 - finetune_value))`
                // (ModSlayer.java:802): computed in i64; the Java `int`
                // product cannot overflow for real rates/values.
                let div = self.mixspeed as i64 * ((1536 - inst.finetune_value) as i64);
                inst.finetune_rate = (22748294283264i64 / div) as i32;
                inst.period_low_limit = 113;
                inst.period_high_limit = 856;
            }
        }

        if self.numtracks > 8 {
            self.vol_shift = 2;
        } else if self.numtracks > 4 {
            self.vol_shift = 1;
        } else {
            self.vol_shift = 0;
        }

        if !self.bit16 {
            self.make_vol_table8();
        }
    }
}


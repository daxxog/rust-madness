//! `modslayer` — ProTracker software mixer (`ModSlayer`) and its μ-law table.
//!
//! Faithful port of `reference/vineflower/ModSlayer.java` (820 lines).
//! Constructor roles (ModSlayer.java:505, via RadicalMod.java:37-39 —
//! `RadicalMod(path, var2, var3, var4)` builds
//! `ModSlayer(mod, var3, var2, var4)`):
//!
//! * `rate` → `samplingrate` (output Hz; 8400 stage 1, 9000 stage 2),
//! * `tempo` → `gain` (mixer gain staging; 350 stage 1, 370 stage 2),
//! * `x` → `def_bpm` (initial beats per minute; 135 stage 1, 145 stage 2).
//!
//! [`ModSlayer::turnbytes`] renders the whole song (one loop, `nloops = 1`)
//! to μ-law bytes via `linear2ulawclip` (UlawUtils.java:8197-8207). The two
//! unrelated `linear2ulaw` overloads (:8209-8215) are the rest of the
//! `UlawUtils` surface; the engine never calls them, the mirror pins do.
//!
//! Notes on items NOT carried over (all unreferenced by the Java engine,
//! hence behaviorally inert):
//!
//! * `VERSION`, `COPYRIGHT`, `MIX_BUF_SIZE`, `DEF_TEMPO_NTSC/PAL`,
//!   `DEF_BPM_NTSC/PAL`, `MIDCRATE`, `MAX_SAMPLES`, `MAX_TRACKS`,
//!   `EFF_*` (the engine tests literal bits 1/2/4/8/16/32; the two high
//!   bits 64/128 are never tested), `S3M_MAGIC1/2`, `S3M_INSTR2`
//!   (`LoadMod` never sets `Mod.s3m`), `period_set_step`, `sunfmt`,
//!   `ERROR_SHIFT`, `ERROR_MASK` (mask/shift inlined as 12/4095 literals,
//!   as in Java), `ratediv` (the literal `22748294283264` is kept inline
//!   at its single use site in `startplaying`).
//! * `S2U_LUT` is NOT standard G.711 μ-law (780/8192 entries differ from
//!   the textbook encoder for the same input), so it is transcribed
//!   literally: generated by `tools/gen-s2u-lut.py` from
